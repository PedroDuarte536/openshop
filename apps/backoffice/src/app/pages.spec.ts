import { Pages } from './pages';
import { mount, button } from './testing/harness';

const sys = (k: string) => ({ id: `s-${k}`, slug: `system-${k}`, title: k, system: k });
describe('Pages page', () => {
  it('opens the creator when there are no own pages yet, and creates one from a template', async () => {
    const m = await mount(Pages);
    const nav = vi.spyOn(m.router, 'navigate').mockResolvedValue(true);
    await m.reply('GET', '/api/pages', [sys('product'), sys('category'), sys('search')]);
    for (const k of ['product', 'category', 'search']) await m.reply('GET', `/api/pages/s-${k}`, { ...sys(k), theme: {}, nodes: [] });
    expect(m.all('.pcard').length).toBe(3);
    expect(m.text()).toContain('No pages yet');
    expect(m.el.querySelector('.newpage')).not.toBeNull();
    await m.click(m.all('.tcard')[1]);
    await m.type('input[name=title]', 'About Us!');
    expect((m.el.querySelector('input[name=slug]') as HTMLInputElement).value).toBe('about-us');
    await m.click(button(m.el, 'Create and open builder'));
    await m.reply('POST', '/api/pages', {}, 409);
    expect(m.text('[role=alert]')).toBe('That address is already used by another page.');
    await m.click(button(m.el, 'Create and open builder'));
    await m.reply('POST', '/api/pages', { error: 'invalid' }, 400);
    expect(m.text('[role=alert]')).toBe('invalid');
    await m.click(button(m.el, 'Create and open builder'));
    const req = await m.reply('POST', '/api/pages', { id: 'new' });
    expect(req.request.body.slug).toBe('about-us');
    expect(req.request.body.nodes.length).toBeGreaterThan(2);
    expect(nav).toHaveBeenCalledWith(['/pages', 'new']);
    await m.click(button(m.el, 'Close'));
    expect(m.el.querySelector('.newpage')).toBeNull();
  });
  it('changes addresses, makes the front page and deletes pages', async () => {
    const m = await mount(Pages);
    const pages = [{ id: 'a', slug: 'about', title: 'About' }, { id: 'h', slug: 'home', title: 'Home' }];
    await m.reply('GET', '/api/pages', pages);
    expect(m.text()).toContain('Front page');
    const about = () => m.all('.pcard').find((c) => c.textContent!.includes('About'))!;
    await m.click(button(about(), 'Change address'));
    const input = () => about().querySelector('.addr input') as HTMLInputElement;
    await m.type('.addr input', 'Our Story');
    expect(input().value).toBe('our-story');
    await m.click(button(about(), 'Save'));
    await m.reply('PATCH', '/api/pages/a', {}, 409);
    expect(m.text('[role=alert]')).toBe('That address is already used by another page.');
    await m.click(button(about(), 'Save'));
    await m.reply('PATCH', '/api/pages/a', {}, 500);
    expect(m.text('[role=alert]')).toBe('Could not change the address.');
    await m.type('.addr input', '');
    await m.click(button(about(), 'Save'));
    expect(m.text('[role=alert]')).toBe('Type an address first.');
    await m.type('.addr input', 'about');
    await m.click(button(about(), 'Save'));
    expect(about().querySelector('.addr input')).toBeNull();
    await m.click(button(about(), 'Change address'));
    input().dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape' })); await m.settle();
    expect(about().querySelector('.addr input')).toBeNull();
    await m.click(button(about(), 'Change address'));
    await m.type('.addr input', 'story');
    input().dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' })); await m.settle();
    await m.reply('PATCH', '/api/pages/a', {});
    await m.reply('GET', '/api/pages', pages);
    await m.click(button(about(), 'Make front page'));
    await m.reply('PATCH', '/api/pages/a', {}, 409);
    expect(m.text('[role=alert]')).toContain('Another page is already the front page');
    await m.click(button(about(), 'Delete'));
    await m.click(button(about(), 'Click to confirm'));
    await m.reply('DELETE', '/api/pages/a', null);
    await m.reply('GET', '/api/pages', [pages[1]]);
    expect(m.all('.pcard').length).toBe(1);
  });
});
